#!/usr/bin/env python3
"""P1 plots and tables from results/runs.csv.

    python3 analysis/p1_plots.py [results/runs.csv] [outdir]

Makes (in outdir, default results/plots/):
  p1_sizes.png     ns per cell-update vs grid size (tag 'sizes'), cache limits marked
  p1_flags.png     compiler-flag variants, 2048x2048 (tags 'flags_*')
  p1_opt.png       kernel code variants (tags 'opt_*'), if present
  p1_tables.md     baseline, size sweep and flags tables (mean +- std of the repeats)

Cache sizes are per core on fortran (AMD EPYC 9755, Zen 5): L2 1 MiB, L3 32 MiB
shared by one 8-core CCD (lscpu in results/logs/p1_sizes_*.out). Bytes per cell
in the time loop: two float32 buffers + one int8 city cell = 9 B.
"""
import sys
from pathlib import Path

import matplotlib
matplotlib.use("Agg")
import matplotlib.pyplot as plt
import pandas as pd

CSV = Path(sys.argv[1] if len(sys.argv) > 1 else "results/runs.csv")
OUT = Path(sys.argv[2] if len(sys.argv) > 2 else "results/plots")
OUT.mkdir(parents=True, exist_ok=True)

BLUE, INK, INK2, GRID, SURF = "#2a78d6", "#0b0b0b", "#52514e", "#e4e3df", "#fcfcfb"
BYTES_PER_CELL = 9
L2, L3 = 1 * 2**20, 32 * 2**20

plt.rcParams.update({
    "font.size": 10, "axes.edgecolor": INK2, "axes.labelcolor": INK, "text.color": INK,
    "xtick.color": INK2, "ytick.color": INK2, "axes.spines.top": False,
    "axes.spines.right": False, "figure.facecolor": SURF, "axes.facecolor": SURF,
    "savefig.facecolor": SURF,
})

d = pd.read_csv(CSV)
d["ns"] = 1e9 * d.time_compute / (d.nx * d.ny * d.steps)
stats = (d.groupby(["tag", "nx"])
           .agg(reps=("ns", "size"), ns=("ns", "mean"), ns_std=("ns", "std"),
                t_total=("time_total", "mean"), t_std=("time_total", "std"),
                t_compute=("time_compute", "mean"), t_io=("time_io", "mean"),
                steps=("steps", "first"), node=("node", "first"),
                checksums=("checksum", "nunique"))
           .reset_index())
assert (stats.checksums == 1).all(), "repeats gave different checksums"

# ---------------- size sweep ----------------
s = stats[stats.tag == "sizes"].sort_values("nx")
fig, ax = plt.subplots(figsize=(7, 4))
ws = BYTES_PER_CELL * (s.nx + 2) ** 2
for lim, name in [(L2, "L2 (1 MiB/core)"), (L3, "L3 (32 MiB/CCD)")]:
    n_lim = (lim / BYTES_PER_CELL) ** 0.5
    ax.axvline(n_lim, color=INK2, lw=1, ls=(0, (3, 3)))
    ax.text(n_lim * 1.04, 0.715, f"{name}\nfull at n ≈ {n_lim:.0f}", color=INK2, fontsize=8, va="bottom")
ax.errorbar(s.nx, s.ns, yerr=s.ns_std.fillna(0), color=BLUE, lw=2, marker="o", ms=6,
            mec=SURF, mew=1.5, capsize=3)
ax.set_xscale("log", base=2)
ax.set_xticks(s.nx)
ax.set_xticklabels([str(n) for n in s.nx], rotation=45)
ax.set_ylim(0.7, max(1.0, s.ns.max() * 1.05))
ax.set_xlabel("Grid size n (n × n cells)")
ax.set_ylabel("Compute time per cell update (ns)")
ax.set_title("Serial solver: time per cell update vs grid size\n"
             f"fortran (EPYC 9755), -O3 -march=native, mean ± std of {int(s.reps.min())} runs",
             fontsize=10, loc="left")
ax.grid(axis="y", color=GRID, lw=0.8)
ax.set_axisbelow(True)
ax.annotate(f"{s.ns.iloc[0]:.2f} ns", (s.nx.iloc[0], s.ns.iloc[0]), textcoords="offset points",
            xytext=(0, -16), ha="center", fontsize=8, color=INK)
ax.annotate(f"{s.ns.iloc[-1]:.2f} ns", (s.nx.iloc[-1], s.ns.iloc[-1]), textcoords="offset points",
            xytext=(0, 9), ha="center", fontsize=8, color=INK)
fig.tight_layout()
fig.savefig(OUT / "p1_sizes.png", dpi=200)
plt.close(fig)

# ---------------- compiler flags ----------------
order = ["flags_O2", "flags_O3", "flags_O3_native", "flags_O3_native_fma"]
labels = {"flags_O2": "-O2", "flags_O3": "-O3", "flags_O3_native": "-O3 -march=native",
          "flags_O3_native_fma": "-O3 -march=native\n-ffp-contract=fast"}
f = stats[stats.tag.isin(order)].set_index("tag").loc[order].reset_index()
base = f.loc[f.tag == "flags_O2", "t_compute"].iloc[0]
f["speedup"] = base / f.t_compute
fig, ax = plt.subplots(figsize=(7, 3.6))
y = range(len(f))[::-1]
ax.barh(list(y), f.t_compute, xerr=f.t_std.fillna(0), color=BLUE, height=0.55, capsize=3)
for yi, (t, sp, e) in zip(y, zip(f.t_compute, f.speedup, f.t_std.fillna(0))):
    ax.text(t + e + base * 0.03, yi, f"{t:.2f} s  ({sp:.2f}×)", va="center", fontsize=9, color=INK)
ax.set_yticks(list(y))
ax.set_yticklabels([labels[t] for t in f.tag])
ax.set_xlim(0, base * 1.35)
ax.set_xlabel("Compute time (s), 2048 × 2048, 2000 steps")
ax.set_title("Compiler flags (speed-up vs -O2), fortran, mean of 3 runs", fontsize=10, loc="left")
ax.grid(axis="x", color=GRID, lw=0.8)
ax.set_axisbelow(True)
fig.tight_layout()
fig.savefig(OUT / "p1_flags.png", dpi=200)
plt.close(fig)

# ---------------- tables ----------------
def fmt(m, sd, p=3):
    return f"{m:.{p}f} ± {0 if pd.isna(sd) else sd:.{p}f}"

lines = ["# P1 results (generated by analysis/p1_plots.py)", ""]
b = stats[stats.tag == "baseline"].sort_values("nx")
lines += ["## Baseline (serial, 2000 steps, -O3 -march=native)", "",
          "| Grid | Total time (s) | Compute (s) | I/O (s) | ns / cell update | Node |",
          "|---|---|---|---|---|---|"]
for r in b.itertuples():
    lines.append(f"| {r.nx}×{r.nx} | {fmt(r.t_total, r.t_std, 2)} | {r.t_compute:.2f} | {r.t_io:.3f} | "
                 f"{fmt(r.ns, r.ns_std)} | {r.node} |")
lines += ["", "## Problem-size sweep (about 4e9 cell updates per run)", "",
          "| n | Steps | Working set (MiB) | Fits in | ns / cell update |", "|---|---|---|---|---|"]
for r in s.itertuples():
    w = BYTES_PER_CELL * (r.nx + 2) ** 2
    where = "L2" if w <= L2 else ("L3" if w <= L3 else "memory")
    lines.append(f"| {r.nx} | {r.steps} | {w / 2**20:.1f} | {where} | {fmt(r.ns, r.ns_std)} |")
lines += ["", "## Compiler flags (2048×2048, 2000 steps)", "",
          "| Flags | Compute (s) | Speed-up vs -O2 | ns / cell update |", "|---|---|---|---|"]
for r in f.itertuples():
    lines.append(f"| `{labels[r.tag].replace(chr(10), ' ')}` | {r.t_compute:.2f} | {r.speedup:.2f}× | "
                 f"{fmt(r.ns, r.ns_std)} |")
# ---------------- code variants (optional) ----------------
VAR = ["ref", "simd", "pertype", "percell", "permute", "double"]
VLAB = {"ref": "reference (table lookup)", "simd": "+ omp simd", "pertype": "per-type factors",
        "percell": "per-cell coefficient arrays", "permute": "AVX-512 register lookup",
        "double": "double precision"}
o = stats[stats.tag.str.startswith("opt_")].copy()
if len(o):
    o["variant"] = o.tag.str[4:]
    sizes = sorted(o.nx.unique())
    lines += ["", "## Code variants (serial, -O3 -march=native)", "",
              "| Variant | " + " | ".join(f"n={n}: ns/update (speed-up)" for n in sizes) + " |",
              "|---|" + "---|" * len(sizes)]
    for v in [v for v in VAR if v in set(o.variant)]:
        cells = []
        for n in sizes:
            row = o[(o.variant == v) & (o.nx == n)]
            refrow = o[(o.variant == "ref") & (o.nx == n)]
            if len(row) and len(refrow):
                cells.append(f"{row.ns.iloc[0]:.3f} ({refrow.ns.iloc[0] / row.ns.iloc[0]:.2f}×)")
            else:
                cells.append("-")
        lines.append(f"| {VLAB[v]} | " + " | ".join(cells) + " |")
    n_big = max(sizes)
    ob = o[o.nx == n_big].set_index("variant")
    vs = [v for v in VAR if v in ob.index]
    fig, ax = plt.subplots(figsize=(7, 3.8))
    y = list(range(len(vs)))[::-1]
    vals = [ob.loc[v, "ns"] for v in vs]
    ax.barh(y, vals, xerr=[0 if pd.isna(ob.loc[v, "ns_std"]) else ob.loc[v, "ns_std"] for v in vs],
            color=BLUE, height=0.55, capsize=3)
    ref_ns = ob.loc["ref", "ns"]
    errs = [0 if pd.isna(ob.loc[v, "ns_std"]) else ob.loc[v, "ns_std"] for v in vs]
    for yi, v, val, e in zip(y, vs, vals, errs):
        ax.text(val + e + ref_ns * 0.03, yi, f"{val:.2f} ns  ({ref_ns / val:.2f}×)", va="center", fontsize=9)
    ax.set_yticks(y)
    ax.set_yticklabels([VLAB[v] for v in vs])
    ax.set_xlim(0, max(vals) * 1.35)
    ax.set_xlabel(f"Compute time per cell update (ns), {n_big} × {n_big}")
    ax.set_title(f"Kernel code variants (speed-up vs reference), mean of {int(ob.reps.min())} runs", fontsize=10, loc="left")
    ax.grid(axis="x", color=GRID, lw=0.8)
    ax.set_axisbelow(True)
    fig.tight_layout()
    fig.savefig(OUT / "p1_opt.png", dpi=200)
    plt.close(fig)

(OUT / "p1_tables.md").write_text("\n".join(lines) + "\n")
print("\n".join(lines))
print(f"\nwrote {OUT}/p1_sizes.png, p1_flags.png" + (", p1_opt.png" if len(o) else "") + ", p1_tables.md")
